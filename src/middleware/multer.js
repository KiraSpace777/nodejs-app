// Для сховища використаємо метод memoryStorage, який зберігає файли безпосередньо в оперативній памʼяті. Це зручно — ми одразу маємо доступ до вмісту файлу у коді й нам не потрібно спершу зберігати його на диск, а потім читати назад. Недолік такого підходу — підвищене навантаження на RAM. Частково вирішити це можна, обмеживши максимальний розмір завантажуваного файлу.
