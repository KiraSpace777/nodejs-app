import bcrypt from 'bcrypt';
import createHttpError from 'http-errors';
import { User } from '../models/user.js';

import { createSession, setSessionCookies } from '../services/auth.js';
import { Session } from '../models/session.js';

// (4.3) Контролер для реєстрації
// ---------------------------------------------------
export const registerUser = async (req, res) => {
  const { email, password } = req.body;

  const existingUser = await User.findOne({ email });
  if (existingUser) {
    throw createHttpError(400, 'Email in use');
  }

  // Хешуємо пароль (4.6)
  const hashedPassword = await bcrypt.hash(password, 10);

  // Створюємо користувача (4.6 - Хешування паролів)
  const newUser = await User.create({
    email,
    password: hashedPassword,
  });

  // Створюємо нову сесію, (4.12) Cесії / Використання в контролерах
  const newSession = await createSession(newUser._id);

  //  Викликаємо, передаємо об'єкт відповіді та сесію, (4.15) Cookies / Додаємо встановлення cookie у контролери
  setSessionCookies(res, newSession);

  // Тут далі будемо додавати логіку створення користувача
  // Поки що відповідаємо порожнім об'єктом
  // res.status(201).json({});

  // Відправляємо дані користувача (без пароля) у відповіді (4.6 - Хешування паролів)
  res.status(201).json(newUser);
};

// (4.8) Контролер логіну
// ---------------------------------------------------
export const loginUser = async (req, res) => {
  const { email, password } = req.body;

  // Перевіряємо чи користувач з такою поштою існує
  const user = await User.findOne({ email });
  if (!user) {
    throw createHttpError(401, 'Invalid credentials');
  }

  // Порівнюємо хеші паролів
  const isValidPassword = await bcrypt.compare(password, user.password);
  if (!isValidPassword) {
    throw createHttpError(401, 'Invalid credentials');
  }

  // Видаляємо стару сесію користувача (4.12) Cесії / Використання в контролерах
  await Session.deleteOne({ userId: user._id });

  // Створюємо нову сесію (4.12) Cесії / Використання в контролерах
  const newSession = await createSession(user._id);

  //  Викликаємо, передаємо об'єкт відповіді та сесію, (4.15) Cookies / Додаємо встановлення cookie у контролери
  setSessionCookies(res, newSession);

  res.status(200).json(user);
};

// (4.16) Контролер логауту користувачів
// ---------------------------------------------------
export const logoutUser = async (req, res) => {
  const { sessionId } = req.cookies;

  if (sessionId) {
    await Session.deleteOne({ _id: sessionId });
  }

  res.clearCookie('sessionId');
  res.clearCookie('accessToken');
  res.clearCookie('refreshToken');

  res.status(204).send();
};

// (4.18) Контролер оновлення сесії (аутентифікація)
// ---------------------------------------------------
export const refreshUserSession = async (req, res) => {
  const { sessionId, refreshToken } = req.cookies;

  if (!sessionId || !refreshToken) {
    throw createHttpError(401, 'Missing session credentials');
  }

  // 1. Знаходимо поточну сесію за id сесії та рефреш токеном
  const session = await Session.findOne({
    _id: sessionId,
    refreshToken,
  });

  // 2. Якщо такої сесії нема, повертаємо помилку
  if (!session) {
    throw createHttpError(401, 'Session not found');
  }

  // 3. Якщо сесія існує, перевіряємо валідність рефреш токена
  const isSessionTokenExpired = session.refreshTokenValidUntil < new Date();

  // Якщо термін дії рефреш токена вийшов,
  // видаляємо сесію і повертаємо помилку
  if (isSessionTokenExpired) {
    await session.deleteOne();
    res.clearCookie('sessionId');
    res.clearCookie('accessToken');
    res.clearCookie('refreshToken');
    throw createHttpError(401, 'Session token expired');
  }

  // 4. Якщо всі перевірки пройшли добре, видаляємо поточну сесію
  await session.deleteOne();

  // 5. Створюємо нову сесію та додаємо кукі
  const newSession = await createSession(session.userId);
  setSessionCookies(res, newSession);

  res.status(200).json({
    message: 'Session refreshed',
  });
};

