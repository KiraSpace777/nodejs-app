export const registerUser = async (req, res) => {
  const { email, password } = req.body;

  const existingUser = await User.findOne({ email });
  if (existingUser) {
    throw createHttpError(400, 'Email in use');
  }

  // Хешуємо пароль (4.6)
  const hashedPassword = await bcrypt.hash(password, 10);

  // Створюємо користувача (4.6 - Хешування паролів)
  const newUser = await User.create({
    email,
    password: hashedPassword,
  });

  // Створюємо нову сесію, (4.12) Cесії / Використання в контролерах
  const newSession = await createSession(newUser._id);

  //  Викликаємо, передаємо об'єкт відповіді та сесію, (4.15) Cookies / Додаємо встановлення cookie у контролери
  setSessionCookies(res, newSession);

  // Тут далі будемо додавати логіку створення користувача
  // Поки що відповідаємо порожнім об'єктом
  // res.status(201).json({});

  // Відправляємо дані користувача (без пароля) у відповіді (4.6 - Хешування паролів)
  res.status(201).json(newUser);
};

// (4.8) Контролер логіну
// ---------------------------------------------------
export const loginUser = async (req, res) => {
  const { email, password } = req.body;

  // Перевіряємо чи користувач з такою поштою існує
  const user = await User.findOne({ email });
  if (!user) {
    throw createHttpError(401, 'Invalid credentials');
  }

  // Порівнюємо хеші паролів
  const isValidPassword = await bcrypt.compare(password, user.password);
  if (!isValidPassword) {
    throw createHttpError(401, 'Invalid credentials');
  }

  // Видаляємо стару сесію користувача (4.12) Cесії / Використання в контролерах
  await Session.deleteOne({ userId: user._id });

  // Створюємо нову сесію (4.12) Cесії / Використання в контролерах
  const newSession = await createSession(user._id);

  //  Викликаємо, передаємо об'єкт відповіді та сесію, (4.15) Cookies / Додаємо встановлення cookie у контролери
  setSessionCookies(res, newSession);

  res.status(200).json(user);
};

// (4.16) Контролер логауту користувачів
