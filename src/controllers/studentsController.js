export const getStudentById = async (req, res) => {
  const { studentId } = req.params;

  // (4.24.2) Створюємо запит до колекції враховуючи "Приватні дані", додаємо до запиту умову user._id, використаємо властивість req.user, яку ми отримуємо завдяки middleware authenticate
  // заміняємо метод "Student.findById" на "Student.findOne"
  // const student = await Student.findById(studentId);
  // -------------------------------------------------
  const student = await Student.findOne({
    _id: studentId,
    userId: req.user._id,
  });

  // Додаємо базову обробку помилки замість обробника res.status(404) // ПОМИЛКА 404
  // та throw new Error(), через пакет http-errors та функцію createHttpError () у файлі // src/controllers/studentsController.js
  // оновимо відповідно і файл "// src/middleware/errorHandler.js"
  // -------------------------------------------------
  if (!student) {
    throw createHttpError(404, 'Student not found');
  }

  res.status(200).json(student);
};

