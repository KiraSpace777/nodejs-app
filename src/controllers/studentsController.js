// Маршрут GET /students : отримати всіх студентів
// ===============================================================
export const getStudents = async (req, res) => {
  // (3.8-9) Отримуємо параметри пагінації і задаємо дефолтні значення
  const {
    page = 1,
    perPage = 10,
    gender,
    minAvgMark,
    search,
    // Отримуємо значення параметрів сортування
    // дефолтне сортування по _id Варіанти напрямків:
    // 1, "asc" = "ascending" → сортування за зростанням (від меншого до більшого);
    // 1, "desc", "descending" → сортування за спаданням (від більшого до меншого).
    sortBy = '_id',
    sortOrder = 'asc',
  } = req.query;
  const skip = (page - 1) * perPage;

  // (3.8) Створюємо базовий запит до колекції (const studentsQuery = Student.find();)
  // (4.24.1) Створюємо запит до колекції враховуючи "Приватні дані", додаємо до запиту умову user._id
  const studentsQuery = Student.find({ userId: req.user._id });

  // (3.10) Пошук по частині імені (за допомогою $regex)
  if (search) {
    studentsQuery.where({
      name: { $regex: search, $options: 'i' },
    });
  }

  // (3.9) Будуємо фільтр
  // (3.9.1) додає умову для фільтрації за статтю, якщо параметр переданий.
  if (gender) {
    studentsQuery.where('gender').equals(gender);
  }
  // (3.9.2) додає умову для фільтрації за середнім балом (беремо тільки тих, у кого avgMark ≥ minAvgMark).
  if (minAvgMark) {
    studentsQuery.where('avgMark').gte(minAvgMark);
  }

  // (3.8) Виконуємо одразу два запити паралельно:
  // Promise.all([...]) — запускаємо підрахунок (countDocuments) і отримання списку студентів одночасно, щоб не робити два послідовних запити.
  // .clone() — потрібен у Mongoose, щоб один і той самий запит можна було виконати двічі (для підрахунку і для вибірки).
  const [totalItems, students] = await Promise.all([
    studentsQuery.clone().countDocuments(),
    studentsQuery
      .skip(skip)
      .limit(perPage)
      // Додаємо сортування в ланцюжок методів квері
      .sort({ [sortBy]: sortOrder }),
  ]);

  // (3.8) Обчислюємо загальну кількість «сторінок»
  const totalPages = Math.ceil(totalItems / perPage);

  res.status(200).json({
    page,
    perPage,
    totalItems,
    totalPages,
    students,
  });

  // (3.9) У результаті ми отримуємо список студентів із врахуванням пагінації та фільтрів, а також додаткову інформацію: скільки всього студентів (totalItems) і скільки сторінок (totalPages).
};

