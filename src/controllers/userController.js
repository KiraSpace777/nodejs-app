// Оновлюємо метод updateUserAvatar, щоб зберігати новий аватар у Cloudinary і записувати його URL у базу даних
// У цьому контролері ми робимо кілька кроків:
// -------------------------
// 1. Перевірка наявності файлу. Якщо користувач не передав файл — повертаємо помилку 400 Bad Request.
// 2. Виклик saveFileToCloudinary. Функція завантажує зображення у Cloudinary і повертає об’єкт із даними про файл. У ньому є, зокрема:
// -------------------------
// secure_url — безпечне посилання на зображення, яке можна використовувати на фронтенді.
// public_id — унікальний ідентифікатор файлу у Cloudinary.
// format, resource_type, bytes та інші службові поля.
// -------------------------
// 3. Оновлення користувача. Ми шукаємо користувача за його _id (береться з req.user._id, встановленого в процесі аутентифікації). Далі виконуємо findOneAndUpdate, щоб записати нову адресу аватара у властивість avatar.
// 4. Опція { returnDocument: "after" }. Вона гарантує, що у змінну user потрапить уже оновлений об’єкт користувача.
// 5. Фінальна відповідь. У відповідь клієнт отримує JSON з ключем url, де лежить новий аватар користувача.
//
// Таким чином, після завантаження зображення у Cloudinary, користувач одразу бачить оновлений аватар у своєму профілі.
